String VisionSystemClientR4::formatMission(int type, const String& rawValue) const {
  bool ok = false;
  int msg = parseInteger(rawValue, ok);
  String value = ok ? String(msg) : rawValue;
  String label = "value";

  if (_teamType == CRASH_SITE) {
    if (type == DIRECTION) {
      label = "abnormality direction";
      if (ok) {
        if (msg == 0) value = "+x";
        else if (msg == 1) value = "-x";
        else if (msg == 2) value = "+y";
        else if (msg == 3) value = "-y";
        else value = "unknown";
      }
    } else if (type == LENGTH) label = "abnormal-side length (mm)";
    else if (type == HEIGHT) label = "abnormal-side height (mm)";
  } else if (_teamType == DATA) {
    if (type == CYCLE) label = "duty cycle (%)";
    else if (type == MAGNETISM) {
      label = "disk magnetism";
      if (ok) value = (msg == MAGNETIC) ? "MAGNETIC" :
                      (msg == NOT_MAGNETIC) ? "NOT MAGNETIC" : "unknown";
    }
  } else if (_teamType == MATERIAL) {
    if (type == WEIGHT) {
      label = "material weight";
      if (ok) value = (msg == HEAVY) ? "HEAVY" :
                      (msg == MEDIUM) ? "MEDIUM" :
                      (msg == LIGHT) ? "LIGHT" : "unknown";
    } else if (type == MATERIAL_TYPE) {
      label = "material type";
      if (ok) value = (msg == FOAM) ? "FOAM" :
                      (msg == PLASTIC) ? "PLASTIC" : "unknown";
    }
  } else if (_teamType == FIRE) {
    if (type == NUM_CANDLES) label = "candle count";
    else if (type == TOPOGRAPHY) {
      label = "topography";
      if (ok) value = (msg == TOP_A) ? "A" : (msg == TOP_B) ? "B" :
                      (msg == TOP_C) ? "C" : "unknown";
    }
  } else if (_teamType == WATER) {
    if (type == DEPTH) label = "water depth (mm)";
    else if (type == WATER_TYPE) {
      label = "water type";
      if (ok) value = (msg == FRESH_UNPOLLUTED) ? "FRESH UNPOLLUTED" :
                      (msg == FRESH_POLLUTED) ? "FRESH POLLUTED" :
                      (msg == SALT_UNPOLLUTED) ? "SALTY UNPOLLUTED" :
                      (msg == SALT_POLLUTED) ? "SALTY POLLUTED" : "unknown";
    }
  } else if (_teamType == SEED) {
    if (type == LOCATION) {
      label = "plot locations";
      if (ok) value = (msg == BOTH) ? "BOTH" : (msg == NEITHER) ? "NEITHER" :
                      (msg == ADJACENT) ? "ADJACENT" :
                      (msg == DIAGONAL) ? "DIAGONAL" : "unknown";
    }
  } else if (_teamType == HYDROGEN) {
    if (type == VOLTAGE_OUTPUT) label = "voltage output";
    else if (type == LED_COLOR) {
      label = "LED color";
      if (ok) value = (msg == WHITE) ? "WHITE" : (msg == RED) ? "RED" :
                      (msg == YELLOW) ? "YELLOW" : (msg == GREEN) ? "GREEN" :
                      (msg == BLUE) ? "BLUE" : "unknown";
    }
  }

  String result = "MISSION MESSAGE: ";
  result += label;
  result += " = ";
  result += value;
  result += '\n';
  return result;
}

