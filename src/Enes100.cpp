bool parseMacString(const std::string& text, uint8_t out[6]) {
  unsigned int v[6] = {0};
  if (sscanf(text.c_str(), "%x:%x:%x:%x:%x:%x",
             &v[0], &v[1], &v[2], &v[3], &v[4], &v[5]) != 6) {
    return false;
  }
  for (uint8_t i = 0; i < 6; ++i) {
    if (v[i] > 0xFF) return false;
    out[i] = static_cast<uint8_t>(v[i]);
  }
  return true;
}

