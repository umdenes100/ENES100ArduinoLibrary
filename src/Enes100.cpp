bool VisionSystemClientR4::enqueueRaw(const char* message, uint8_t kind) {
  if (!message || !_txMutex) {
    ++_droppedMessages;
    return false;
  }

  SemaphoreHandle_t mutex = asSemaphore(_txMutex);
  if (xSemaphoreTake(mutex, pdMS_TO_TICKS(10)) != pdTRUE) {
    ++_droppedMessages;
    return false;
  }

  if (_txCount >= TX_QUEUE_DEPTH) {
    ++_droppedMessages;
    xSemaphoreGive(mutex);
    debug("[Enes100] print queue full; packet dropped");
    return false;
  }

  _txQueue[_txHead].kind = kind;
  strncpy(_txQueue[_txHead].text, message, TX_TEXT_SIZE - 1);
  _txQueue[_txHead].text[TX_TEXT_SIZE - 1] = '\0';
  _txHead = static_cast<uint8_t>((_txHead + 1) % TX_QUEUE_DEPTH);
  ++_txCount;
  xSemaphoreGive(mutex);
  return true;
}

bool VisionSystemClientR4::popRaw(char* out, size_t outLen, uint8_t& kind) {
  if (!out || outLen == 0 || !_txMutex) return false;

  SemaphoreHandle_t mutex = asSemaphore(_txMutex);
  if (xSemaphoreTake(mutex, pdMS_TO_TICKS(10)) != pdTRUE) return false;

  if (_txCount == 0) {
    xSemaphoreGive(mutex);
    return false;
  }

  kind = _txQueue[_txTail].kind;
  strncpy(out, _txQueue[_txTail].text, outLen - 1);
  out[outLen - 1] = '\0';
  _txTail = static_cast<uint8_t>((_txTail + 1) % TX_QUEUE_DEPTH);
  --_txCount;
  xSemaphoreGive(mutex);
  return true;
}

