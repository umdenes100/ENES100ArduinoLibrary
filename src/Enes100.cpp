void VisionSystemClientR4::handleIncoming(const String& message) {
  if (message.indexOf("\"op\"") < 0) return;

  String op;
  if (!extractQuoted(message, "\"op\"", op)) return;

  if (op == "aruco") handleAruco(message);
  else if (op == "ping") handlePing(message);
}

void VisionSystemClientR4::handleAruco(const String& message) {
  bool visible;
  float x, y, theta;

  bool okV = extractBool(message, "\"is_visible\"", visible) ||
             extractBool(message, "\"visible\"", visible);
  bool okX = extractFloat(message, "\"x\"", x);
  bool okY = extractFloat(message, "\"y\"", y);
  bool okT = extractFloat(message, "\"theta\"", theta);

  if (!(okV && okX && okY && okT)) return;

  _visible = visible;
  if (visible) {
    _x = x;
    _y = y;
    _theta = theta;
    location.x = x;
    location.y = y;
    location.theta = theta;
  } else {
    _x = _y = _theta = -1.0f;
    location.x = location.y = location.theta = -1.0;
  }
}

void VisionSystemClientR4::handlePing(const String& message) {
  String status;
  if (!extractQuoted(message, "\"status\"", status)) return;
  if (status == "ping") sendPing("pong");
}

