bool VisionSystemClientR4::startBackgroundTask() {
  if (_taskRunning) return true;

  if (!_txMutex) {
    // ArduinoCore-renesas 1.6.x builds FreeRTOS with mutex support disabled,
    // so xSemaphoreCreateMutex() is not available.  A binary semaphore works
    // well here because this object only needs short mutual exclusion around
    // the print queue.  Newly-created binary semaphores start empty, so give
    // it once to put it in the unlocked state.
    SemaphoreHandle_t gate = xSemaphoreCreateBinary();
    if (!gate) return false;
    xSemaphoreGive(gate);
    _txMutex = static_cast<void*>(gate);
  }

  TaskHandle_t handle = nullptr;
  BaseType_t rc = xTaskCreate(taskThunk,
                              "ENES100",
                              ENES100_STACK_WORDS,
                              this,
                              2,
                              &handle);
  if (rc != pdPASS) return false;

  _taskHandle = static_cast<void*>(handle);
  _taskRunning = true;

  // With EARLY_AUTOSTART_FREERTOS the Arduino sketch thread runs above this
  // task by default. Lower the calling sketch thread so ENES100 networking can
  // still run even if loop() contains no delay().
  if (xTaskGetSchedulerState() == taskSCHEDULER_RUNNING) {
    vTaskPrioritySet(nullptr, 1);
  }

  return true;
}

void VisionSystemClientR4::taskThunk(void* arg) {
  static_cast<VisionSystemClientR4*>(arg)->taskLoop();
}

void VisionSystemClientR4::taskLoop() {
  debug("[Enes100] network task started");

  while (_configured && !discoverIdentity()) {
    debug("[Enes100] ERROR: this UNO R4 WiFi MAC is not in the credential table");
    vTaskDelay(pdMS_TO_TICKS(3000));
  }

  uint32_t lastWifiAttempt = 0;
  uint32_t lastWsAttempt = 0;
  uint32_t lastPing = 0;
  uint32_t lastPoseRequest = 0;
  uint8_t missedPongs = 0;

  while (_configured) {
    const uint32_t now = millis();

    bool wifiNow = (WiFi.status() == WL_CONNECTED);
    if (!wifiNow) {
      _wifiConnected = false;
      if (_wsConnected) disconnectWebSocket();

      if (lastWifiAttempt == 0 || (now - lastWifiAttempt) >= WIFI_RETRY_MS) {
        lastWifiAttempt = now;
        if (connectWifi()) {
          lastWsAttempt = 0;
          missedPongs = 0;
        }
      }

      vTaskDelay(pdMS_TO_TICKS(40));
      continue;
    }
    _wifiConnected = true;

    if (!_wsConnected || !_wsPtr || !_wsPtr->connected()) {
      if (_wsConnected) disconnectWebSocket();

      if (lastWsAttempt == 0 || (now - lastWsAttempt) >= WS_RETRY_MS) {
        lastWsAttempt = now;
        if (connectWebSocket()) {
          lastPing = millis();
          lastPoseRequest = 0;
          missedPongs = 0;
        }
      }

      vTaskDelay(pdMS_TO_TICKS(20));
      continue;
    }

    char outgoing[TX_TEXT_SIZE];
    uint8_t outgoingKind = TX_PRINT;
    while (popRaw(outgoing, sizeof(outgoing), outgoingKind)) {
      bool sent = (outgoingKind == TX_CAPTURE)
                    ? sendCapturePacket(outgoing)
                    : sendPrintPacket(outgoing);
      if (!sent) {
        disconnectWebSocket();
        break;
      }
    }
    if (!_wsConnected) continue;

    if (lastPoseRequest == 0 || (now - lastPoseRequest) >= POSE_REQUEST_PERIOD_MS) {
      if (!sendArucoRequest()) {
        disconnectWebSocket();
        continue;
      }
      lastPoseRequest = now;
    }

    if ((now - lastPing) >= PING_PERIOD_MS) {
      if (!sendPing("ping")) {
        disconnectWebSocket();
        continue;
      }
      lastPing = now;
      if (++missedPongs >= PING_MISS_LIMIT) {
        debug("[Enes100] ping timeout; reconnecting WebSocket");
        disconnectWebSocket();
        missedPongs = 0;
        continue;
      }
    }

    int size = _wsPtr->parseMessage();
    if (size > 0 && _wsPtr->messageType() == TYPE_TEXT) {
      String message = _wsPtr->readString();

      String status;
      if (extractQuoted(message, "\"status\"", status) && status == "pong") {
        missedPongs = 0;
      }
      handleIncoming(message);
    }

    vTaskDelay(pdMS_TO_TICKS(10));
  }

  disconnectWebSocket();
  _taskRunning = false;
  _taskHandle = nullptr;
  vTaskDelete(nullptr);
}

bool VisionSystemClientR4::discoverIdentity() {
  if (_profileMatched) return true;

  auto loadProfileForCurrentMac = [this]() -> bool {
    formatMac(_mac, _macText);

    if (_debugEnabled) {
      Serial.print("[Enes100] board MAC: ");
      Serial.println(_macText);
    }

    for (size_t i = 0; i < DEVICE_PROFILE_COUNT; ++i) {
      const DeviceProfile& p = DEVICE_PROFILES[i];
      if (!sameMac(_mac, p.mac)) continue;

      strncpy(_hostname, p.hostname, sizeof(_hostname) - 1);
      _hostname[sizeof(_hostname) - 1] = '\0';
      strncpy(_wifiPassword, p.password, sizeof(_wifiPassword) - 1);
      _wifiPassword[sizeof(_wifiPassword) - 1] = '\0';
      _profileMatched = true;

      if (_debugEnabled) {
        Serial.print("[Enes100] profile: ");
        Serial.println(_hostname);
      }
      return true;
    }
    return false;
  };

  // FAST PATH: WiFiS3's public macAddress() only returns the station MAC when
  // the ESP32-S3 is already in station mode. A full scan used to be used only
  // to force that mode, but a scan costs several seconds. WiFiS3 exposes its
  // modem command layer, so put the coprocessor directly into station mode and
  // query MACSTA immediately. This normally completes in a few milliseconds.
  memset(_mac, 0, sizeof(_mac));
  std::string response;
  modem.begin();
  bool stationModeReady = modem.write(std::string(PROMPT(_MODE)),
                                      response,
                                      "%s%d\r\n",
                                      CMD_WRITE(_MODE),
                                      1);
  if (stationModeReady) {
    response.clear();
    bool macRead = modem.write(std::string(PROMPT(_MACSTA)),
                               response,
                               CMD_READ(_MACSTA));
    if (macRead && parseMacString(response, _mac) && loadProfileForCurrentMac()) {
      return true;
    }
  }

  // Compatibility fallback for a future WiFiS3 implementation where the
  // internal command path changes. This is intentionally not the normal path.
  debug("[Enes100] fast MAC lookup failed; falling back to WiFi scan");
  WiFi.scanNetworks();
  WiFi.macAddress(_mac);
  if (loadProfileForCurrentMac()) return true;

  _profileMatched = false;
  return false;
}

bool VisionSystemClientR4::connectWifi() {
  if (!_profileMatched && !discoverIdentity()) return false;

  // A MAC may be provisioned before its network password is assigned.
  // Treat that as an incomplete profile instead of attempting an empty
  // password and waiting for the normal association timeout.
  if (_wifiPassword[0] == '\0') {
    _wifiConnected = false;
    debug("[Enes100] profile matched, but no WiFi password is provisioned");
    return false;
  }

  WiFi.disconnect();
  delay(2);
  WiFi.setHostname(_hostname);

  if (_debugEnabled) {
    Serial.print("[Enes100] joining ");
    Serial.print(WIFI_SSID);
    Serial.print(" as ");
    Serial.println(_hostname);
  }

  // FAST PATH: call the WiFiS3 modem's BEGINSTA command directly. The normal
  // WiFi.begin() wrapper starts the same ESP32-S3 association and then performs
  // its own blocking status loop. Starting it here lets this task immediately
  // poll at a controlled interval and proceed the instant DHCP completes.
  const uint32_t start = millis();
  std::string response;
  modem.begin();
  bool joinStarted = modem.write(std::string(PROMPT(_BEGINSTA)),
                                 response,
                                 "%s%s,%s\r\n",
                                 CMD_WRITE(_BEGINSTA),
                                 WIFI_SSID,
                                 _wifiPassword);
  if (!joinStarted) {
    _wifiConnected = false;
    debug("[Enes100] failed to start WiFi association");
    return false;
  }

  while ((millis() - start) < WIFI_CONNECT_TIMEOUT_MS) {
    if (WiFi.status() == WL_CONNECTED) {
      _wifiConnected = true;
      if (_debugEnabled) {
        Serial.print("[Enes100] WiFi connected in ");
        Serial.print(millis() - start);
        Serial.print(" ms, IP: ");
        Serial.println(WiFi.localIP());
      }
      return true;
    }
    vTaskDelay(pdMS_TO_TICKS(25));
  }

  _wifiConnected = false;
  WiFi.disconnect();
  debug("[Enes100] WiFi join timed out");
  return false;
}

void VisionSystemClientR4::chooseServerForRoom() {
  switch (_room) {
    case 1116: strcpy(_server, "10.112.9.114"); break;
    case 1120: strcpy(_server, "10.112.9.115"); break;
    case 1201: strcpy(_server, "10.112.9.116"); break;
    default:   strcpy(_server, "10.112.9.116"); break;
  }
}

bool VisionSystemClientR4::connectWebSocket() {
  disconnectWebSocket();

  if (_tcpPtr) {
    delete _tcpPtr;
    _tcpPtr = nullptr;
  }

  _tcpPtr = new WiFiClient();
  if (!_tcpPtr) return false;

  _wsPtr = new WebSocketClient(*_tcpPtr, _server, WS_PORT);
  if (!_wsPtr) {
    delete _tcpPtr;
    _tcpPtr = nullptr;
    return false;
  }

  _wsPtr->setHttpResponseTimeout(5000);

  if (_debugEnabled) {
    Serial.print("[Enes100] connecting ws://");
    Serial.print(_server);
    Serial.print(':');
    Serial.print(WS_PORT);
    Serial.println(WS_PATH);
  }

  int result = _wsPtr->begin(WS_PATH);
  if (result != 0) {
    if (_debugEnabled) {
      Serial.print("[Enes100] WebSocket handshake failed: ");
      Serial.println(result);
    }
    disconnectWebSocket();
    return false;
  }

  _wsConnected = true;
  debug("[Enes100] WebSocket connected");

  if (!sendBeginPacket()) {
    disconnectWebSocket();
    return false;
  }
  sendArucoRequest();
  return true;
}

void VisionSystemClientR4::disconnectWebSocket() {
  _wsConnected = false;
  if (_wsPtr) {
    _wsPtr->stop();
    delete _wsPtr;
    _wsPtr = nullptr;
  }
  if (_tcpPtr) {
    _tcpPtr->stop();
    delete _tcpPtr;
    _tcpPtr = nullptr;
  }
}

bool VisionSystemClientR4::sendText(const char* text) {
  if (!_wsConnected || !_wsPtr || !_tcpPtr || !_wsPtr->connected() || !text) return false;

  // ArduinoHttpClient's WebSocketClient has a small compile-time TX buffer.
  // Send the already-upgraded WebSocket connection directly so normal ENES100
  // messages are not silently truncated by that buffer.
  const size_t len = strlen(text);
  if (len > 1024) return false;

  uint8_t header[4];
  size_t headerLen = 0;
  header[headerLen++] = 0x81; // FIN + text frame

  if (len <= 125) {
    header[headerLen++] = 0x80 | static_cast<uint8_t>(len); // client frames are masked
  } else {
    header[headerLen++] = 0x80 | 126;
    header[headerLen++] = static_cast<uint8_t>((len >> 8) & 0xFF);
    header[headerLen++] = static_cast<uint8_t>(len & 0xFF);
  }

  uint8_t mask[4];
  for (uint8_t i = 0; i < 4; ++i) mask[i] = static_cast<uint8_t>(random(0, 256));

  if (_tcpPtr->write(header, headerLen) != headerLen) return false;
  if (_tcpPtr->write(mask, sizeof(mask)) != sizeof(mask)) return false;

  uint8_t chunk[64];
  size_t offset = 0;
  while (offset < len) {
    size_t n = len - offset;
    if (n > sizeof(chunk)) n = sizeof(chunk);
    for (size_t i = 0; i < n; ++i) {
      chunk[i] = static_cast<uint8_t>(text[offset + i]) ^ mask[(offset + i) & 3];
    }
    if (_tcpPtr->write(chunk, n) != n) return false;
    offset += n;
  }

  return true;
}

