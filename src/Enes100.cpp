bool VisionSystemClientR4::extractFloat(const String& json, const char* key, float& out) {
  int i = json.indexOf(key);
  if (i < 0) return false;
  int colon = json.indexOf(':', i);
  if (colon < 0) return false;
  int j = colon + 1;
  while (j < static_cast<int>(json.length()) && (json[j] == ' ' || json[j] == '\t')) ++j;
  int start = j;
  while (j < static_cast<int>(json.length())) {
    char c = json[j];
    if ((c >= '0' && c <= '9') || c == '-' || c == '+' || c == '.' || c == 'e' || c == 'E') ++j;
    else break;
  }
  if (j <= start) return false;
  out = json.substring(start, j).toFloat();
  return true;
}

bool VisionSystemClientR4::extractBool(const String& json, const char* key, bool& out) {
  int i = json.indexOf(key);
  if (i < 0) return false;
  int colon = json.indexOf(':', i);
  if (colon < 0) return false;
  String tail = json.substring(colon + 1);
  tail.trim();
  if (tail.startsWith("true")) { out = true; return true; }
  if (tail.startsWith("false")) { out = false; return true; }
  return false;
}

bool VisionSystemClientR4::extractQuoted(const String& json, const char* key, String& out) {
  int i = json.indexOf(key);
  if (i < 0) return false;
  int colon = json.indexOf(':', i);
  if (colon < 0) return false;
  int quote1 = json.indexOf('"', colon + 1);
  if (quote1 < 0) return false;
  int quote2 = quote1 + 1;
  bool escaped = false;
  for (; quote2 < static_cast<int>(json.length()); ++quote2) {
    char c = json[quote2];
    if (c == '"' && !escaped) break;
    if (c == '\\' && !escaped) escaped = true;
    else escaped = false;
  }
  if (quote2 >= static_cast<int>(json.length())) return false;
  out = json.substring(quote1 + 1, quote2);
  return true;
}

String VisionSystemClientR4::jsonEscape(const char* input) {
  return jsonEscape(String(input ? input : ""));
}

String VisionSystemClientR4::jsonEscape(const String& input) {
  String out;
  out.reserve(input.length() + 8);
  for (size_t i = 0; i < input.length(); ++i) {
    char c = input[i];
    switch (c) {
      case '\\': out += "\\\\"; break;
      case '"':  out += "\\\""; break;
      case '\n': out += "\\n"; break;
      case '\r': out += "\\r"; break;
      case '\t': out += "\\t"; break;
      default:   out += c; break;
    }
  }
  return out;
}

